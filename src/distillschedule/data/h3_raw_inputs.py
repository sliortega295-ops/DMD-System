"""Offline raw previous/current H3 AV -> original cached parser -> PreparedDataset.

Frame directories + stereo PCM WAV and explicitly preencoded original text.
No fake prompt/history, no implicit AV alignment and no Student construction.
The intermediate encoded dataset and native caches are retained as provenance;
only the final original-parser dataset is accepted by the existing CPU trainer.
"""
from copy import deepcopy
import json
from pathlib import Path
import wave

from distillschedule.workloads.best_known.registry import file_sha256, fingerprint
from distillschedule.training.h3_cached_assets import checked_pin, read_json
from distillschedule.training import h3_av_encoder as encoder, h3_av_codec as codec
from .manifest import source_identity, validate_source, frame_paths, resolve_path
from .preparation import _new_output, _publish

SCHEMA = 'distillschedule.original_h3_raw_av_inputs.v1'
require = codec.require


def _file_pin(path):
    path=Path(path).resolve()
    return dict(path=str(path),bytes=path.stat().st_size,sha256=file_sha256(path))


def _prompt(pin):
    """Original text features are required, never generated by this AV codec."""
    import torch
    from safetensors import safe_open
    path=checked_pin(pin)
    require(path.suffix == '.safetensors' and pin['bytes'] <= 90_000_000, 'bounded safe original text features required')
    with safe_open(path,framework='pt',device='cpu') as handle:
        require(set(handle.keys()) == {'prompt_embeds','text_token_tags'}, 'original prompt and text-only tags required')
        e,t=handle.get_slice('prompt_embeds'),handle.get_slice('text_token_tags')
        shape=e.get_shape()
        require(len(shape) == 2 and 0 < shape[0] <= 4096 and shape[1] == 5120 and e.get_dtype() == 'F32'
            and t.get_dtype() == 'I64' and t.get_shape() == [shape[0]], 'original prompt [L,5120] FP32 and int64 tags required')
        embeddings,tags=handle.get_tensor('prompt_embeds'),handle.get_tensor('text_token_tags')
    checked_pin(pin)
    require(bool(torch.isfinite(embeddings).all()) and bool((tags == 1).all()), 'finite original FL2VA text-only prompt required')
    return dict(prompt_embeds=embeddings,text_token_tags=tags)


def _chunk(spec,base,p):
    from PIL import Image
    require(isinstance(spec,dict) and set(spec) == {'video','audio','fps'}
        and isinstance(spec['video'],dict) and set(spec['video']) == {'path','sha256'}, 'explicit raw video/audio/FPS chunk required')
    video=resolve_path(spec['video']['path'],base)
    require(video.is_dir(), 'H3 raw encoder requires an explicit RGB frame directory; extract a video without resampling first')
    vi=source_identity(video,frames=True)
    require(vi['sha256'] == spec['video']['sha256'], 'raw frame content identity changed')
    audio=checked_pin(spec['audio']); ai=source_identity(audio)
    sizes=[]
    for file in frame_paths(video):
        with Image.open(file) as image:sizes.append(image.size)
    require(all(size == sizes[0] for size in sizes), 'raw frames differ; no resize permitted')
    with wave.open(str(audio),'rb') as source:
        require(source.getframerate() == 32000 and source.getnchannels() == 2
            and source.getcomptype() == 'NONE' and source.getsampwidth() in (1,2,3,4), 'stereo PCM 32kHz WAV required')
        count=source.getnframes()
    shape=[len(sizes),sizes[0][1],sizes[0][0],3]
    encoder.admit_geometry(p,shape,count,spec['fps'])
    return dict(video=str(video),audio=str(audio),fps=spec['fps'],shape=shape,samples=count,
                identities=dict(video=vi,audio=ai))


def prepare_inputs(source_manifest, output):
    import torch
    from .decoding import _video, _audio
    from .dataset import PreparedDataset
    from .tensors import tensor_tree
    from . import h3_cached_inputs as cached
    from distillschedule.training import h3_cached_assets as assets
    from distillschedule.reference import diffsynth_h3_cached as provider
    output=_new_output(output)
    path=Path(source_manifest).resolve(); value=read_json(path)
    require(isinstance(value,dict) and set(value) == {'schema_version','encoder','records'}
        and value['schema_version'] == SCHEMA, 'explicit raw H3 AV input schema required')
    config=value['encoder']
    require(isinstance(config,dict) and set(config) == {'manifest'}, 'pinned original encoder manifest required')
    codec_path=checked_pin(config['manifest']); p=encoder.validate_manifest(read_json(codec_path))
    records=value['records']
    require(isinstance(records,list) and 0 < len(records) <= 10_000, 'bounded raw H3 pair inventory required')
    documents=[source_identity(path),source_identity(codec_path),source_identity(Path(__file__)),source_identity(Path(encoder.__file__)),source_identity(Path(codec.__file__))]
    documents += [source_identity(Path(p['source']['root'])/name) for name in p['source']['files']]
    documents += [source_identity(checked_pin(pin)) for pins in p['weights'].values() for pin in pins]
    chunks,ids,expected_geometry=[],set(),None
    for row in records:
        require(isinstance(row,dict) and set(row) == {'id','current','previous','prompt'}
            and isinstance(row['id'],str) and row['id'].strip() and row['id'] not in ids,
            'unique raw sample id with actual previous/current AV and prompt required')
        ids.add(row['id']); text=_prompt(row['prompt'])
        observed=dict(prompt_shape=list(text['prompt_embeds'].shape))
        prompt=source_identity(checked_pin(row['prompt']));documents.append(prompt)
        for role in ('current','previous'):
            desc=_chunk(row[role],path.parent,p)
            shapes=encoder.latent_shapes(desc['shape'],desc['samples'])
            prefix='' if role == 'current' else 'reference_'
            observed[prefix+'video_shape']=shapes['video_latents']
            observed[prefix+'audio_shape']=shapes['audio_latents']
            chunks.append(dict(id=row['id']+'/'+role,pair_id=row['id'],role=role,chunk=desc,prompt=deepcopy(row['prompt'])))
        assets.validate_geometry(observed)
        if expected_geometry is None:expected_geometry=observed
        require(expected_geometry == observed, 'fixed original reference geometry required; bucket different raw shapes explicitly')
    # All source/header checks precede output publication and codec materialization.
    output.parent.mkdir(parents=True,exist_ok=True)
    lock=output.parent/('.'+output.name+'.lock')
    with lock.open('x'):
        try:
            output.mkdir()
            bundle=encoder.build_encoder(config)
            encodings={}
            def produce(row):
                c=row['chunk']
                for identity in c['identities'].values():validate_source(identity)
                pixels,waveform=_video(c['video']),_audio(c['audio'])
                require(list(pixels.shape) == c['shape'] and waveform['samples'].shape[0] == c['samples'], 'raw header changed during encoding')
                result=encoder.encode(bundle,pixels,waveform,fps=c['fps'])
                for identity in c['identities'].values():validate_source(identity)
                encodings[row['id']]=result.pop('encoding')
                result.update(_prompt(row['prompt']))
                return tensor_tree(result)
            code=source_identity(Path(__file__))
            identity=dict(reference='distillschedule.data.h3_raw_inputs:prepare_inputs',sha256=code['sha256'],
                source_path=code['path'],parameters=deepcopy(config),parameters_sha256=fingerprint(config))
            provenance=dict(mode='raw',documents=documents,encoder=identity,
                sources=[dict(id=r['id'],media={**r['chunk']['identities'],'text':source_identity(checked_pin(r['prompt']))}) for r in chunks])
            encoded_path=_publish(output/'encoded',rows=chunks,provenance=provenance,
                metadata=dict(schema_version=SCHEMA,encoder=bundle['metadata'],text='SUPPLIED_ORIGINAL_FEATURES_NOT_ENCODED',
                    roles={r['id']:dict(pair_id=r['pair_id'],role=r['role']) for r in chunks}),produce=produce)
            del bundle
            encoded=PreparedDataset(encoded_path);native=[];geometry=expected_geometry;receipts=[]
            (output/'native-caches').mkdir()
            for i,row in enumerate(records):
                current,previous=encoded.sample(2*i),encoded.sample(2*i+1)
                require(torch.equal(current['prompt_embeds'],previous['prompt_embeds'])
                    and torch.equal(current['text_token_tags'],previous['text_token_tags']), 'prompt changed across raw chunk pair')
                raw=dict(input_latents=current['video_latents'],audio_input_latents=current['audio_latents'],
                    ref_video_latents=previous['video_latents'],ref_audio_latents=previous['audio_latents'],
                    prompt_embeds=current['prompt_embeds'],text_token_tags=current['text_token_tags'])
                observed=dict(video_shape=list(raw['input_latents'].shape),audio_shape=list(raw['audio_input_latents'].shape),
                    reference_video_shape=list(raw['ref_video_latents'].shape),reference_audio_shape=list(raw['ref_audio_latents'].shape),
                    prompt_shape=list(raw['prompt_embeds'].shape))
                require(geometry == observed, 'fixed original reference geometry required; bucket different raw shapes explicitly')
                cached.canonical_raw(raw,geometry)
                target=output/'native-caches'/f'{i:08d}.pt'
                with target.open('xb') as stream:torch.save(raw,stream)
                native.append(dict(id=row['id'],cache=_file_pin(target)))
                receipts.append(dict(id=row['id'],current=encodings[row['id']+'/current'],previous=encodings[row['id']+'/previous']))
            kind=assets.FIXTURE if p['evidence_kind'] == codec.FIXTURE else assets.REAL
            original=dict(schema_version=cached.SCHEMA,evidence_kind=kind,source=provider.source_identity(),
                precision=assets.PRECISION,geometry=geometry,records=native)
            native_path=output/'original-cached-inputs.json'
            native_path.write_text(json.dumps(original,indent=2,sort_keys=True)+'\n')
            prepared=cached.prepare_inputs(native_path,output/'prepared')
            # Final validation is against ALL original media/encoder files, not only caches.
            encoded.validate(sources=True)
            receipt=dict(schema_version='distillschedule.original_h3_raw_encoding_receipt.v1',status='COMPLETE',
                source=source_identity(path),encoder_manifest=config['manifest'],encoded=source_identity(encoded_path),
                native_inputs=source_identity(native_path),prepared=source_identity(prepared),records=receipts,
                GPU_started=0,quality_validation='NOT_RUN',text='SUPPLIED_ORIGINAL_FEATURES_NOT_SYNTHESIZED')
            (output/'encoding.json').write_text(json.dumps(receipt,indent=2,sort_keys=True)+'\n')
            (output/'_SUCCESS').write_text(fingerprint(receipt)+'\n')
            return prepared
        finally:lock.unlink(missing_ok=True)
